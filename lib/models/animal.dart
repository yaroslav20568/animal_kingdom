class Animal {
  final String id;
  final String name;
  final String description;
  final String imageUrl;
  final String habitat;
  final String diet;
  final String lifespan;

  const Animal({
    required this.id,
    required this.name,
    required this.description,
    required this.imageUrl,
    required this.habitat,
    required this.diet,
    required this.lifespan,
  });
}
